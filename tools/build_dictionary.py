def est_value(ipm, min_log, max_log):
    if ipm <= 0:
        return 5
    if max_log <= min_log:
        return 500
    norm = (math.log10(ipm) - min_log) / (max_log - min_log)
    norm = max(0.0, min(1.0, norm))
    return int(round(5 + 995 * norm))


def rarity(ipm):
    if ipm >= 10:
        return "common"
    if ipm >= 1:
        return "uncommon"
    if ipm >= 0.1:
        return "rare"
    if ipm >= 0.01:
        return "epic"
    if ipm >= 0.001:
        return "legendary"
    return "mythic"


