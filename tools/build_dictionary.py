def build(words):
    ips = [w[1] for w in words if w[1] > 0]
    min_log = math.log10(min(ips)) if ips else 0.0
    max_log = math.log10(max(ips)) if ips else 1.0
    out = []
    for w in words:
        lemma, ipm = w[0], w[1]
        pos = w[2] if len(w) >= 3 else ""
        definition = w[3] if len(w) >= 4 else ""
        examples = w[4] if len(w) >= 5 else []
        out.append({
            "id": lemma,
            "lemma": lemma,
            "pos": pos,
            "frequency_ipm": ipm,
            "rarity_tier": rarity(ipm),
            "est_value": est_value(ipm, min_log, max_log),
            "definition": definition,
            "examples": examples,
        })
    return {
        "version": 1,
        "generated_at": datetime.datetime.utcnow().isoformat() + "Z",
        "words": out,
    }


def load_csv(path):
    words = []
    with open(path, encoding="utf-8") as f:
        for row in csv.reader(f):
            if len(row) >= 3:
                try:
                    words.append((row[1].strip(), float(row[2]), "", "", []))
                except ValueError:
                    pass
    return words


def main():
    if len(sys.argv) >= 3:
        words = load_csv(sys.argv[1])
        out_path = sys.argv[2]
    else:
        words = RICH + [(w[0], w[1], "", "", []) for w in PLAIN]
        out_path = "app/src/main/assets/words.json"
    data = build(words)
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    vals = [w["est_value"] for w in data["words"]]
    print("OK: " + str(len(data["words"])) + " слов -> " + out_path)
    print("est_value: min=" + str(min(vals)) + " max=" + str(max(vals)))


if __name__ == "__main__":
    main()
